function formatLocalPrice(usdPrice, langCode = 'en') {
  const curr = currencies[langCode] || currencies.en;
  const localVal = (usdPrice * curr.rate).toFixed(2);
  return `${curr.symbol} ${localVal} (${curr.code})`;
}

function formatUsdPrice(usdPrice) {
  return `$${usdPrice.toFixed(2)} USD`;
}

